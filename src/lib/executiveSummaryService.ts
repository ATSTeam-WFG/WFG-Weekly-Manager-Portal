// A persisted analysis's sections are one of two shapes: the original fixed
// 7-key ReportingAnalysisSections (every analysis generated before this ATS
// migration, kept exactly as before) or the new dynamic-topic AtsReport
// (every analysis generated after it). The two are structurally disjoint —
// legacy carries exactly the 7 named string keys above, ATS carries exactly
// `openingParagraph` + `topics` — so a plain key check reliably tells them
// apart with no ambiguity and no separate shape marker needed.
export type ExecutiveAnalysisSections = ReportingAnalysisSections | AtsReport

// A plain "does .topics exist" check would misclassify malformed persisted
// data (e.g. {openingParagraph: "...", topics: []}, or a topic missing a
// required field) as safely renderable/editable ATS content, when it isn't:
// AtsReportView/AtsTopicsEditForm both assume every topic has a non-empty
// string `title`/`statusSummary`/`next` and a non-empty array of string
// `bullets` to .map() over. This checks exactly that much structure — no
// more — before classifying something as ATS-shaped, so a return of `true`
// here is a genuine guarantee the renderer/editor can safely assume, not
// just a guess based on which top-level keys happen to be present. A
// document that fails this check falls through to the legacy rendering
// branch instead (see ExecutiveAnalysisCard.tsx), which reads it via plain
// object-key lookups that return undefined rather than throwing — so
// malformed persisted data can never crash either branch, only render as
// unexpectedly blank, which should not occur in practice since every write
// path is already gated by the matching SQL validator (see
// supabase/migrations/20260923_executive_analysis_ats_shape.sql).
export function isAtsShapedSections(sections: ExecutiveAnalysisSections): sections is AtsReport {
  const candidate = sections as Partial<AtsReport> | null | undefined
  return (
    typeof candidate?.openingParagraph === 'string' &&
    Array.isArray(candidate.topics) &&
    candidate.topics.length > 0 &&
    candidate.topics.every(
      (topic) =>
        typeof topic === 'object' &&
        topic !== null &&
        typeof topic.title === 'string' &&
        typeof topic.statusSummary === 'string' &&
        typeof topic.next === 'string' &&
        Array.isArray(topic.bullets) &&
        topic.bullets.length > 0 &&
        topic.bullets.every((bullet) => typeof bullet === 'string'),
    )
  )
}

export type ExecutiveSummaryErrorCode =
  | 'UNAUTHORIZED'
  | 'FORBIDDEN'
  | 'NO_SUBMISSIONS'
  | 'INVALID_REQUEST'
  | 'GENERATION_FAILED'
  | 'EDITED_VERSION_EXISTS'
  | 'NOT_FOUND'
  | 'INVALID_SECTIONS'
  | 'UNKNOWN'

// The persisted row shown everywhere this period is viewed — Weekly Summary
// and Reports & Analytics both read and mutate exactly this shape, never a
// separate copy of their own. `generated_sections`/generation & edit
// metadata are database-controlled (see save_executive_analysis_edit /
// revert_executive_analysis / regenerate_executive_analysis) — nothing in
// this client module ever constructs those fields itself.
export interface PersistedExecutiveAnalysis {
  id: string
  periodKey: ReportPeriodKey
  periodStartDate: string
  periodEndDate: string
  periodLabel: string
  generatedSections: ExecutiveAnalysisSections
  sections: ExecutiveAnalysisSections
  isEdited: boolean
  generatedAt: string
  generatedBy: string
  editedAt: string | null
  editedBy: string | null
  sourceFingerprint: string
}

interface PersistedExecutiveAnalysisRow {
  id: string
  period_key: ReportPeriodKey
  period_start_date: string
  period_end_date: string
  period_label: string
  generated_sections: ExecutiveAnalysisSections
  sections: ExecutiveAnalysisSections
  is_edited: boolean
  generated_at: string
  generated_by: string
  edited_at: string | null
  edited_by: string | null
  source_fingerprint: string
}

function fromRow(row: PersistedExecutiveAnalysisRow): PersistedExecutiveAnalysis {
  return {
    id: row.id,
    periodKey: row.period_key,
    periodStartDate: row.period_start_date,
    periodEndDate: row.period_end_date,
    periodLabel: row.period_label,
    generatedSections: row.generated_sections,
    sections: row.sections,
    isEdited: row.is_edited,
    generatedAt: row.generated_at,
    generatedBy: row.generated_by,
    editedAt: row.edited_at,
    editedBy: row.edited_by,
    sourceFingerprint: row.source_fingerprint,
  }
}

// RPC/Postgres exceptions in this app are raised as 'CODE: message' (see the
// three executive_analyses functions) — this pulls the leading code back out
// so callers get the same typed ExecutiveSummaryError shape regardless of
// whether the failure came from the HTTP endpoint or a direct .rpc() call.
function parseRpcError(message: string | undefined): ExecutiveSummaryError {
  const match = message?.match(/^([A-Z_]+):\s*(.*)$/)
  if (match) {
    const [, code, detail] = match
    return new ExecutiveSummaryError(code as ExecutiveSummaryErrorCode, detail || message || 'Something went wrong.')
  }
  return new ExecutiveSummaryError('UNKNOWN', message || 'Something went wrong.')
}

export class ExecutiveSummaryError extends Error {
  code: ExecutiveSummaryErrorCode

  constructor(code: ExecutiveSummaryErrorCode, message: string) {
    super(message)
    this.code = code
  }
}

// Delegates to the shared session helper, translated into this module's own
// error type so existing callers/UI here are unaffected by the refactor.
async function getValidAccessToken(): Promise<string> {
  try {
    return await getValidAccessTokenShared()
  } catch (err) {
    const message = err instanceof SessionError ? err.message : 'You must be signed in to generate an analysis.'
    throw new ExecutiveSummaryError('UNAUTHORIZED', message)
  }
}

// The browser sends only the period type, offset, and (when re-generating
// over saved edits) an explicit confirmation — never raw report text, and
// never a client-computed date list or fingerprint. The server independently
// recomputes the range, fetches the reports, calls the AI, and persists the
// result via regenerate_executive_analysis(); this returns that persisted
// row, not a transient in-memory result.
export async function generateReportingAnalysis(
  periodKey: ReportPeriodKey,
  offset: number,
  confirmOverwrite = false,
): Promise<PersistedExecutiveAnalysis> {
  const accessToken = await getValidAccessToken()

  let response: Response
  try {
    response = await fetch('/api/executive-summary', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${accessToken}`,
      },
      body: JSON.stringify({ periodKey, offset, confirmOverwrite }),
    })
  } catch {
    throw new ExecutiveSummaryError('UNKNOWN', 'Could not reach the server. Please check your connection.')
  }

  const responseBody = await response.json().catch(() => null)

  if (!response.ok) {
    const code: ExecutiveSummaryErrorCode = responseBody?.error ?? 'UNKNOWN'
    const message = responseBody?.message ?? 'Something went wrong while generating the analysis.'
    throw new ExecutiveSummaryError(code, message)
  }

  return fromRow(responseBody as PersistedExecutiveAnalysisRow)
}

// Direct, RLS-scoped read — genuinely read-only, so this doesn't need to go
// through a server endpoint or an RPC. Returns null if no analysis has ever
// been generated for this exact period yet (not an error).
export async function fetchPersistedAnalysis(
  periodKey: ReportPeriodKey,
  periodStartDate: string,
): Promise<PersistedExecutiveAnalysis | null> {
  const { data, error } = await supabase
    .from('executive_analyses')
    .select(
      'id, period_key, period_start_date, period_end_date, period_label, generated_sections, sections, is_edited, generated_at, generated_by, edited_at, edited_by, source_fingerprint',
    )
    .eq('period_key', periodKey)
    .eq('period_start_date', periodStartDate)
    .maybeSingle()

  if (error) {
    console.error('Failed to fetch persisted executive analysis:', error.message)
    return null
  }
  if (!data) return null
  return fromRow(data as PersistedExecutiveAnalysisRow)
}

// Save Edit — a narrow RPC. is_edited/edited_at/edited_by are set inside
// Postgres, never accepted as parameters here; generated_sections and
// generation metadata are structurally untouched by this call (see
// save_executive_analysis_edit).
export async function saveEditedAnalysis(
  analysisId: string,
  sections: ExecutiveAnalysisSections,
): Promise<PersistedExecutiveAnalysis> {
  const { data, error } = await supabase.rpc('save_executive_analysis_edit', {
    p_analysis_id: analysisId,
    p_sections: sections,
  })
  if (error) throw parseRpcError(error.message)
  return fromRow(data as PersistedExecutiveAnalysisRow)
}

// Revert — a narrow RPC. No sections value is sent from the browser at all;
// the function reads generated_sections from the row itself server-side.
export async function revertToOriginal(analysisId: string): Promise<PersistedExecutiveAnalysis> {
  const { data, error } = await supabase.rpc('revert_executive_analysis', {
    p_analysis_id: analysisId,
  })
  if (error) throw parseRpcError(error.message)
  return fromRow(data as PersistedExecutiveAnalysisRow)
}
