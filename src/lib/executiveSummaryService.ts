// One shared shape for AI-generated reporting analysis, used by both the
// Weekly Summary page (period 'weekly') and Reports & Analytics (all six
// periods) — a single secure pipeline rather than parallel implementations.
export interface ReportingAnalysisSections {
  executiveSummary: string
  keyPriorities: string
  majorWins: string
  challengesRisks: string
  challengeProgress: string
  opportunities: string
  prioritiesGoingForward: string
}

// Deterministic, app-computed statistics — never generated by the AI.
export interface ReportingAnalysisStats {
  uniqueManagers: number
  expectedReports: number
  submittedReports: number
  draftReports: number
  missingReports: number
  completionPct: number
}

export interface ReportingAnalysisResult {
  sections: ReportingAnalysisSections
  stats: ReportingAnalysisStats
  periodLabel: string
}

